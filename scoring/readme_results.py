#!/usr/bin/env python3
"""README.md results block, generated from results/summary.csv (scoring/summarize.py) and results/stats_arms.csv
(scoring/stats.py) so no number is typed by hand.

Rewrites only the text between the START and END markers in README.md: accuracy (NCA tasks and T3d), reproducibility
(distinct parameter-value sets over valid runs, the paper's measure; not output-file hashes), cost per run, and the T2
case study. Every number is a valid-run aggregate as those scripts computed it. Stdlib only.
Usage: readme_results.py   (run scoring/summarize.py and scoring/stats.py first)
"""
import csv, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SUMMARY = os.path.join(ROOT, "results", "summary.csv")
ARM_STATS = os.path.join(ROOT, "results", "stats_arms.csv")
README = os.path.join(ROOT, "README.md")
START = "<!-- results:start (generated by scoring/readme_results.py - do not edit) -->"
END = "<!-- results:end -->"
ARMS = {"A0": "No tools", "A1": "PMxAgent 1.0.0 (MCP) offered", "A1b": "A1 + PMxAgent's shipped CLAUDE.md",
        "A2": "Skills, knowledge only", "A3": "Skills + script", "A4": "Skills + script"}
SHORT = {"T1_nca": "T1", "T2_case": "T2", "T3a_messy": "T3a", "T3b_blq": "T3b", "T3c_units": "T3c",
         "T3d_oral": "T3d", "T3e_large": "T3e"}
ACCURACY = ["T1_nca", "T3a_messy", "T3b_blq", "T3c_units", "T3e_large", "T3d_oral"]
NCA = ACCURACY[:-1]   # tasks with parameter-value sets (T3d has 3 typical values, T2 its own measures)
ALL = ["T1_nca", "T2_case", "T3a_messy", "T3b_blq", "T3c_units", "T3e_large", "T3d_oral"]
DASH = "–"


def table(by, models, tasks, cell, title, note):
    """One markdown table: a row per arm that has any of `tasks`, a column per task, cell(by[arm, task]);
    `models` = {(arm, task): model} from summary.csv."""
    arms = [a for a in ARMS if any((a, t) in by for t in tasks)]
    model = {a: next(models[a, t] for t in ALL if (a, t) in models) for a in arms}
    L = [f"### {title}", note, "",
         "| Arm | Setup | Model | " + " | ".join(SHORT[t] for t in tasks) + " |",
         "|---|---|---|" + "---|" * len(tasks)]
    for a in arms:
        L.append(f"| {a} | {ARMS[a]} | {model[a]} | "
                 + " | ".join(cell(by[a, t]) if (a, t) in by else DASH for t in tasks) + " |")
    return L + [""]


def render(rows, arm_stats):
    by = {(r["arm"], r["task"]): r for r in rows}
    models = {k: r["model"] for k, r in by.items()}
    sets = {(r["arm"], r["task"]): r for r in arm_stats if r["distinct_value_sets"] not in ("", "n/a")}
    acc = lambda r: f"{r['accuracy_overall']} ({r['n_runs']})" if r["accuracy_overall"] else DASH
    cost = lambda r: f"{float(r['cost_usd_per_run'].split(' ± ')[0]):.2f}" if r["cost_usd_per_run"] else DASH
    L = table(by, models, ACCURACY, acc, "Accuracy",
              "Mean ± SD over valid runs (n). NCA tasks: the paper's metric (% of subject-parameters within 1% of "
              "PKanalix, mean of 7 parameters). T3d: % of 3 typical values within 1% of the analytical truth.")
    L += table(sets, models, NCA, lambda r: f"{r['distinct_value_sets']}/{r['n']}", "Reproducibility",
               "Distinct sets of NCA parameter values / valid runs (1/n = identical results in every run).")
    L += table(by, models, ALL, cost, "Cost", "Mean list-price cost per run, USD (estimated from token use; runs used a "
                                      "subscription).")
    t2 = [a for a in ARMS if (a, "T2_case") in by]
    L += ["### Simulation case study (T2)", "No ground truth: completion and internal consistency of the reported "
          "summary (mean ± SD over runs).", "",
          "| Arm | Runs | Completed | Summary consistent (%) |", "|---|---|---|---|"]
    L += [f"| {a} | {by[a, 'T2_case']['n_runs']} | {by[a, 'T2_case']['t2_completed'] or DASH} | "
          f"{by[a, 'T2_case']['t2_summary_consistent_pct'] or DASH} |" for a in t2]
    return "\n".join(L)


def splice(text, block):
    """`text` with everything between START and END replaced by `block`; ValueError if a marker is missing."""
    i, j = text.find(START), text.find(END)
    if i < 0 or j < i:
        raise ValueError(f"README markers not found: {START} ... {END}")
    return text[:i + len(START)] + "\n" + block + "\n" + text[j:]


def main():
    rows = list(csv.DictReader(open(SUMMARY, newline="")))
    arm_stats = list(csv.DictReader(open(ARM_STATS, newline="")))
    text = open(README).read()
    open(README, "w").write(splice(text, render(rows, arm_stats)))
    print(f"README.md results block: {len(rows)} summary rows")


if __name__ == "__main__":
    main()
