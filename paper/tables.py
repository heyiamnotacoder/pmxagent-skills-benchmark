#!/usr/bin/env python3
"""LaTeX tables for the paper, generated from results/*.csv -> paper/tables/*.tex. No number is typed by hand.

tab_accuracy_<task>.tex  per-parameter + overall accuracy, mean over runs (NCA tasks)
tab_stats_<task>.tex     pre-specified comparisons (results/stats.csv, from scoring/stats.py)
tab_effort_<task>.tex    cost, wall time, turns, tool calls, tool errors per run (results/runs.csv, valid runs)
Usage: python3 paper/tables.py   (run scoring/stats.py first)
"""
import csv, os, statistics as st
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, "results")
OUT = os.path.join(ROOT, "paper", "tables")
ARMS = ["A0", "A1", "A2", "A3", "A4"]
PARAMS = [("Cmax", "$C_\\mathrm{max}$"), ("Tmax", "$t_\\mathrm{max}$"), ("AUClast", "AUC$_\\mathrm{last}$"),
          ("AUCINF_obs", "AUC$_{\\infty,\\mathrm{obs}}$"), ("HL", "$t_{1/2}$"), ("CL", "CL"), ("Vz", "$V_z$")]
NCA = {"T1_nca", "T3a_messy", "T3b_blq", "T3c_units", "T3e_large"}


def f(x):
    try:
        return float(x)
    except (TypeError, ValueError):
        return None


def msd(xs, nd):
    xs = [x for x in xs if x is not None]
    if not xs:
        return "--"
    if len(xs) == 1:
        return f"{xs[0]:.{nd}f}"
    return f"{st.mean(xs):.{nd}f} $\\pm$ {st.stdev(xs):.{nd}f}"


def sg(x):
    return f"{x:+.2f}".replace("-", "$-$")


def write(name, lines):
    os.makedirs(OUT, exist_ok=True)
    open(os.path.join(OUT, name), "w").write("% generated by paper/tables.py - do not edit\n" + "\n".join(lines) + "\n")
    print("wrote paper/tables/" + name)


WORD = {"0": "zero", "1": "one", "2": "two", "3": "three", "4": "four", "5": "five"}


def macro(task, arm, what):
    """\\numToneAzeroAcc style names (LaTeX macro names cannot hold digits)."""
    t = task.split("_")[0]
    return "\\num" + "".join(WORD.get(c, c) for c in t).title().replace(" ", "") + \
        "".join(WORD.get(c, c) for c in arm).title() + what


def main():
    scores = defaultdict(lambda: defaultdict(list))
    for r in csv.DictReader(open(os.path.join(RES, "scores.csv"))):
        scores[r["task"]][r["arm"]].append(r)
    runs = {r["runid"]: r for r in csv.DictReader(open(os.path.join(RES, "runs.csv")))}
    stats = list(csv.DictReader(open(os.path.join(RES, "stats.csv")))) if os.path.exists(os.path.join(RES, "stats.csv")) else []

    nums = []
    for task, by_arm in sorted(scores.items()):
        arms = [a for a in ARMS if by_arm.get(a)]
        for a in arms:
            rs = by_arm[a]
            ov = [f(r["overall"]) for r in rs if f(r.get("overall")) is not None]
            rr = [runs[r["runid"]] for r in rs if r["runid"] in runs]
            cost = [f(x["cost_usd"]) for x in rr if f(x["cost_usd"]) is not None]
            wall = [f(x["duration_s"]) / 60 for x in rr if f(x["duration_s"]) is not None]
            vals = {"N": str(len(rs)), "Acc": f"{st.mean(ov):.2f}" if ov else "--",
                    "AccSD": f"{st.stdev(ov):.2f}" if len(ov) > 1 else "--",
                    "Cost": f"{st.mean(cost):.2f}" if cost else "--", "Wall": f"{st.mean(wall):.1f}" if wall else "--"}
            nums += [f"\\newcommand{{{macro(task, a, k)}}}{{{v}}}" for k, v in vals.items()]
        if task in NCA:
            L = ["\\begin{tabular}{l r " + "r" * len(PARAMS) + " r r}", "\\toprule",
                 "Arm & $n$ & " + " & ".join(lab for _, lab in PARAMS) + " & Overall & Range \\\\", "\\midrule"]
            for a in arms:
                rs = by_arm[a]
                cells = [f"{st.mean([f(r[p + '_pct']) for r in rs]):.1f}" for p, _ in PARAMS]
                ov = [f(r["overall"]) for r in rs]
                L.append(f"{a} & {len(rs)} & " + " & ".join(cells) +
                         f" & {st.mean(ov):.2f} & {min(ov):.2f}--{max(ov):.2f} \\\\")
            L += ["\\bottomrule", "\\end{tabular}"]
            write(f"tab_accuracy_{task}.tex", L)

        L = ["\\begin{tabular}{l r r r r r}", "\\toprule",
             "Arm & Cost/run (USD) & Wall time (min) & Turns & Tool calls & Tool errors \\\\", "\\midrule"]
        for a in arms:
            rr = [runs[r["runid"]] for r in by_arm[a] if r["runid"] in runs]
            L.append(f"{a} & {msd([f(x['cost_usd']) for x in rr], 3)} & "
                     f"{msd([f(x['duration_s']) / 60 for x in rr if f(x['duration_s']) is not None], 1)} & "
                     f"{msd([f(x['num_turns']) for x in rr], 1)} & {msd([f(x['tool_calls']) for x in rr], 1)} & "
                     f"{msd([f(x['tool_errors']) for x in rr], 1)} \\\\")
        L += ["\\bottomrule", "\\end{tabular}"]
        write(f"tab_effort_{task}.tex", L)

        rows = [r for r in stats if r["task"] == task]
        if rows:
            L = ["\\begin{tabular}{l c r c r c}", "\\toprule",
                 "Comparison & $n$ & Difference (pp) & 95\\% CI & $p$ (perm.) & Within $\\pm$1 pp \\\\", "\\midrule"]
            for r in rows:
                p = float(r["p_perm"])
                ps = "$<$0.0001" if p < 1e-4 else f"{p:.4f}"
                L.append(f"{r['comparison'].replace('-', '$-$')} & {r['n_x']} vs {r['n_y']} & {sg(float(r['diff']))} & "
                         f"{sg(float(r['ci_lo']))} to {sg(float(r['ci_hi']))} & {ps} & "
                         f"{'yes' if r['equivalent_1pp'] == 'True' else 'no'} \\\\")
            L += ["\\bottomrule", "\\end{tabular}"]
            write(f"tab_stats_{task}.tex", L)
            for r in rows:
                x, y = r["comparison"].split(" - ")
                k = macro(task, x, "Vs" + "".join(WORD.get(c, c) for c in y).title())
                nums += [f"\\newcommand{{{k}Diff}}{{{sg(float(r['diff']))}}}",
                         f"\\newcommand{{{k}CI}}{{{sg(float(r['ci_lo']))} to {sg(float(r['ci_hi']))}}}"]
    write("numbers.tex", nums)


if __name__ == "__main__":
    main()
