#!/usr/bin/env python3
"""LaTeX tables for the paper, generated from results/*.csv -> paper/tables/*.tex. No number is typed by hand.

tab_accuracy_<task>.tex  per-parameter + overall accuracy, mean over runs (NCA tasks)
tab_stats_<task>.tex     pre-specified comparisons (results/stats.csv, from scoring/stats.py)
tab_effort_<task>.tex    cost, wall time, turns, tool calls, tool errors per run (results/runs.csv, valid runs)
numbers.tex              \\num... macros; per arm also `Distinct`/`DistinctFiles` (parameter-value / output-file sets),
                         `NptsRuns`/`NptsMatch`/`LzErr`/`LzErrDiffer`/`LzErrMatch` (terminal-point match, NCA tasks; §26),
                         `PmxRuns`/`PmxKnown` (runs with >=1 PMxAgent tool call / runs scanned), and, from stats.py,
                         `Unscorable`/`AccPostHoc` (post hoc, logs/deviations.md §17; only where a run was unscorable),
                         `Acc<Regime>`/`N<Regime>` and `...Vs...<Regime>Diff/CI` (isolation-regime sensitivity, §15).
Usage: python3 paper/tables.py   (run scoring/stats.py first)
"""
import csv, os, statistics as st
from collections import Counter, defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, "results")
OUT = os.path.join(ROOT, "paper", "tables")
ARMS = ["A0", "A1", "A1b", "A2", "A3", "A4"]
PARAMS = [("Cmax", "$C_\\mathrm{max}$"), ("Tmax", "$t_\\mathrm{max}$"), ("AUClast", "AUC$_\\mathrm{last}$"),
          ("AUCINF_obs", "AUC$_{\\infty,\\mathrm{obs}}$"), ("HL", "$t_{1/2}$"), ("CL", "CL"), ("Vz", "$V_z$")]
NCA = {"T1_nca", "T3a_messy", "T3b_blq", "T3c_units", "T3e_large"}


def f(x):
    try:
        return float(x)
    except (TypeError, ValueError):
        return None


def msd(xs, nd):
    xs = [x for x in xs if x is not None]
    if not xs:
        return "--"
    if len(xs) == 1:
        return f"{xs[0]:.{nd}f}"
    return f"{st.mean(xs):.{nd}f} $\\pm$ {st.stdev(xs):.{nd}f}"


def sg(x):
    return f"{x:+.2f}".replace("-", "$-$")


def write(name, lines):
    os.makedirs(OUT, exist_ok=True)
    open(os.path.join(OUT, name), "w").write("% generated by paper/tables.py - do not edit\n" + "\n".join(lines) + "\n")
    print("wrote paper/tables/" + name)


WORD = {"0": "zero", "1": "one", "2": "two", "3": "three", "4": "four", "5": "five"}


def macro(task, arm, what):
    """\\numToneAzeroAcc style names (LaTeX macro names cannot hold digits)."""
    t = task.split("_")[0]
    return "\\num" + "".join(WORD.get(c, c) for c in t).title().replace(" ", "") + \
        "".join(WORD.get(c, c) for c in arm).title() + what


def read(name):
    p = os.path.join(RES, name)
    return list(csv.DictReader(open(p))) if os.path.exists(p) else []


def pair_macros(task, comparison, suffix, r):
    """\\num<Task><X>Vs<Y><suffix>Diff / ...CI for one comparison row (stats*.csv)."""
    x, y = comparison.split(" - ")
    k = macro(task, x, "Vs" + "".join(WORD.get(c, c) for c in y).title() + suffix)
    return [f"\\newcommand{{{k}Diff}}{{{sg(float(r['diff']))}}}",
            f"\\newcommand{{{k}CI}}{{{sg(float(r['ci_lo']))} to {sg(float(r['ci_hi']))}}}"]


def main():
    scores = defaultdict(lambda: defaultdict(list))
    for r in csv.DictReader(open(os.path.join(RES, "scores.csv"))):
        scores[r["task"]][r["arm"]].append(r)
    runs = {r["runid"]: r for r in csv.DictReader(open(os.path.join(RES, "runs.csv")))}
    stats = read("stats.csv")
    arm_stats = {(r["task"], r["arm"]): r for r in read("stats_arms.csv")}
    distinct = {k: r["distinct_value_sets"] for k, r in arm_stats.items()}
    files = {(r["task"], r["arm"]): r["n_distinct_outputs"] for r in read("summary.csv")}
    ph_arms = {(r["task"], r["arm"]): r for r in read("stats_posthoc_arms.csv")}

    nums = []
    for task, by_arm in sorted(scores.items()):
        arms = [a for a in ARMS if by_arm.get(a)]
        for a in arms:
            rs = by_arm[a]
            ov = [f(r["overall"]) for r in rs if f(r.get("overall")) is not None]
            rr = [runs[r["runid"]] for r in rs if r["runid"] in runs]
            cost = [f(x["cost_usd"]) for x in rr if f(x["cost_usd"]) is not None]
            wall = [f(x["duration_s"]) / 60 for x in rr if f(x["duration_s"]) is not None]
            vals = {"N": str(len(rs)), "Acc": f"{st.mean(ov):.2f}" if ov else "--",
                    "AccSD": f"{st.stdev(ov):.2f}" if len(ov) > 1 else "--",
                    "Cost": f"{st.mean(cost):.2f}" if cost else "--", "Wall": f"{st.mean(wall):.1f}" if wall else "--"}
            if distinct.get((task, a), "n/a") != "n/a":
                vals["Distinct"] = distinct[(task, a)]
            if files.get((task, a)):
                vals["DistinctFiles"] = files[(task, a)]
            vals.update(terminal_point_macros(arm_stats.get((task, a), {})))
            ph = ph_arms.get((task, a))   # only tasks where some run was unscorable (stats.py, post hoc)
            if ph:
                vals["Unscorable"] = ph["n_dropped"]
                vals["AccPostHoc"] = f"{float(ph['mean']):.2f}" if ph["mean"] else "--"
            pmx = [int(f(r["pmxagent_tool_calls"])) for r in rs if f(r.get("pmxagent_tool_calls")) is not None]
            if pmx:
                vals["PmxRuns"], vals["PmxKnown"] = str(sum(n > 0 for n in pmx)), str(len(pmx))
            http = [int(f(r["pmxagent_http_calls"])) for r in rs if f(r.get("pmxagent_http_calls")) is not None]
            if http:
                vals["PmxHttpRuns"] = str(sum(n > 0 for n in http))
            nums += [f"\\newcommand{{{macro(task, a, k)}}}{{{v}}}" for k, v in vals.items()]
        if task in NCA:
            L = ["\\begin{tabular}{l r " + "r" * len(PARAMS) + " r r r}", "\\toprule",
                 "Arm & $n$ & " + " & ".join(lab for _, lab in PARAMS) + " & Overall & Range & Points match$^*$ \\\\",
                 "\\midrule"]
            for a in arms:
                rs = by_arm[a]
                cells = [f"{st.mean([f(r[p + '_pct']) for r in rs]):.1f}" for p, _ in PARAMS]
                ov = [f(r["overall"]) for r in rs]
                L.append(f"{a} & {len(rs)} & " + " & ".join(cells) +
                         f" & {st.mean(ov):.2f} & {min(ov):.2f}--{max(ov):.2f} & "
                         f"{terminal_point_cell(arm_stats.get((task, a), {}))} \\\\")
            L += ["\\bottomrule", "\\end{tabular}"]
            write(f"tab_accuracy_{task}.tex", L)

        L = ["\\begin{tabular}{l r r r r r}", "\\toprule",
             "Arm & Cost/run (USD) & Wall time (min) & Turns & Tool calls & Tool errors \\\\", "\\midrule"]
        for a in arms:
            rr = [runs[r["runid"]] for r in by_arm[a] if r["runid"] in runs]
            L.append(f"{a} & {msd([f(x['cost_usd']) for x in rr], 3)} & "
                     f"{msd([f(x['duration_s']) / 60 for x in rr if f(x['duration_s']) is not None], 1)} & "
                     f"{msd([f(x['num_turns']) for x in rr], 1)} & {msd([f(x['tool_calls']) for x in rr], 1)} & "
                     f"{msd([f(x['tool_errors']) for x in rr], 1)} \\\\")
        L += ["\\bottomrule", "\\end{tabular}"]
        write(f"tab_effort_{task}.tex", L)

        rows = [r for r in stats if r["task"] == task]
        if rows:
            L = ["\\begin{tabular}{l c r c r c}", "\\toprule",
                 "Comparison & $n$ & Difference (pp) & 95\\% CI & $p$ (perm.) & Within $\\pm$1 pp \\\\", "\\midrule"]
            for r in rows:
                p = float(r["p_perm"])
                ps = "$<$0.0001" if p < 1e-4 else f"{p:.4f}"
                L.append(f"{r['comparison'].replace('-', '$-$')} & {r['n_x']} vs {r['n_y']} & {sg(float(r['diff']))} & "
                         f"{sg(float(r['ci_lo']))} to {sg(float(r['ci_hi']))} & {ps} & "
                         f"{'yes' if r['equivalent_1pp'] == 'True' else 'no'} \\\\")
            L += ["\\bottomrule", "\\end{tabular}"]
            write(f"tab_stats_{task}.tex", L)
            for r in rows:
                nums += pair_macros(task, r["comparison"], "", r)
    sec_stats = read("stats_secondary.csv")
    for task in sorted({r["task"] for r in sec_stats}):
        rows = [r for r in sec_stats if r["task"] == task]
        L = ["\\begin{tabular}{l c r c r c}", "\\toprule",
             "Comparison & $n$ & Difference (pp) & 95\\% CI & $p$ (perm.) & Within $\\pm$1 pp \\\\", "\\midrule"]
        for r in rows:
            p = float(r["p_perm"])
            ps = "$<$0.0001" if p < 1e-4 else f"{p:.4f}"
            L.append(f"{r['comparison'].replace('-', '$-$')} & {r['n_x']} vs {r['n_y']} & {sg(float(r['diff']))} & "
                     f"{sg(float(r['ci_lo']))} to {sg(float(r['ci_hi']))} & {ps} & "
                     f"{'yes' if r['equivalent_1pp'] == 'True' else 'no'} \\\\")
        L += ["\\bottomrule", "\\end{tabular}"]
        write(f"tab_stats_secondary_{task}.tex", L)
    for r in sec_stats:   # secondary arm A1b (§21): \\numToneAonebVsAoneSecondaryDiff
        nums += pair_macros(r["task"], r["comparison"], "Secondary", r)
    for r in read("stats_posthoc.csv"):   # post hoc (logs/deviations.md §17): \\numToneAtwoVsAonePostHocDiff
        nums += pair_macros(r["task"], r["comparison"], "PostHoc", r)
    for r in read("stats_sensitivity_arms.csv"):   # isolation regime (§15): \\numToneAoneAccIsolated, ...NUser
        reg = r["regime"].title()
        nums += [f"\\newcommand{{{macro(r['task'], r['arm'], 'Acc' + reg)}}}{{{float(r['mean']):.2f}}}",
                 f"\\newcommand{{{macro(r['task'], r['arm'], 'N' + reg)}}}{{{r['n']}}}"]
    for r in read("stats_sensitivity.csv"):   # \\numToneAtwoVsAoneIsolatedDiff
        nums += pair_macros(r["task"], r["comparison"], r["regime"].title(), r)
    nums += t2_case(scores["T2_case"])
    nums += t2_parser_macros()
    t3_accuracy(scores, distinct)
    t3_stats(stats)
    cost_by_task(scores, runs)
    write("numbers.tex", nums)


def tex_int(x):
    """Integer with LaTeX-safe thousands separators: 1420 -> 1{,}420."""
    return f"{int(x):,}".replace(",", "{,}")


def terminal_point_macros(r):
    """`NptsRuns`, `NptsMatch`, `LzErr`, `LzErrDiffer`, `LzErrMatch` from one stats_arms.csv row (stats.terminal_points; descriptive,
    post hoc, logs/deviations.md §26); nothing without raw files or for non-NCA tasks."""
    if r.get("npts_match_pct") in (None, "", "n/a"):
        return {}
    return {"NptsRuns": r["npts_runs"], "NptsMatch": f"{float(r['npts_match_pct']):.1f}",
            "LzErr": tex_int(r["lz_errors"]), "LzErrDiffer": tex_int(r["lz_errors_npts_differ"]),
            "LzErrMatch": tex_int(r["lz_errors_npts_match"])}


def terminal_point_cell(r):
    """Accuracy-table cell: % of subjects with PKanalix's number of terminal points, pooled over the runs that reported
    it, with that run count when not every run did."""
    m = terminal_point_macros(r)
    if not m:
        return "--"
    return m["NptsMatch"] + ("" if m["NptsRuns"] == r.get("n") else f" ({m['NptsRuns']})")


T3 = ["T3a_messy", "T3b_blq", "T3c_units", "T3d_oral", "T3e_large"]
SHORT = {"T2_case": "T2", "T3a_messy": "T3a", "T3b_blq": "T3b", "T3c_units": "T3c", "T3d_oral": "T3d", "T3e_large": "T3e"}


# PMxAgent's own T2 case-study EC50, h·µg/mL, as printed in its supplement (demo/QC_Report_claude.md): its Claude and
# Cursor runs. Kept as text so the paper quotes the source exactly.
PMX_EC50 = {"Claude": "2,131.1", "Cursor": "2,139.5"}
MATCH_TOL = 0.01   # the benchmark's 1% agreement rule (T1 metric, T2 consistency)


def matches_pmx_ec50(r):
    """One run's EC50, converted to h·µg/mL, within 1% of either published PMxAgent value; None if not converted.
    A per-run comparison with a fixed external value: nothing is averaged or ranged across runs (§24, §25)."""
    v = f(r.get("ec50_h_ug_ml"))
    if v is None:
        return None
    return any(abs(v - p) / p < MATCH_TOL for p in (float(x.replace(",", "")) for x in PMX_EC50.values()))


def t2_parser_macros():
    """\\numTtwoParser{N,Agree,Fixed} from results/t2_parser_check.csv (scoring/check_t2_parser.py, §25)."""
    rows = list(csv.DictReader(open(os.path.join(RES, "t2_parser_check.csv"))))
    return [f"\\newcommand{{\\numTtwoParserN}}{{{len(rows)}}}",
            f"\\newcommand{{\\numTtwoParserAgree}}{{{sum(r['agree'] == 'True' for r in rows)}}}",
            f"\\newcommand{{\\numTtwoParserFixed}}{{{sum(r['unparseable_before'] == 'True' for r in rows)}}}"]


def t2_case(by_arm):
    """T2 has no ground truth (SPEC.md): completion, internal consistency, and spread of EC50 across runs.
    EC50 depends on the PK parameters and units each run chose (the prompt gives neither), so it is summarised as the
    number of distinct values (3 significant digits) and the size of the largest group of identical values, never
    averaged across runs (§24). The descriptive comparison with PMxAgent's own case-study EC50 (issue #7, §25) counts
    runs whose converted EC50 is within 1% of a published value. Writes tab_t2_T2_case.tex; returns
    \\numTtwo<Arm>{Completed,ConsChecked,Cons,ConsAny,EcDistinct,EcModal,EcConv,EcPmx}, \\numTtwoPmxEc<Run>, \\numTtwoRuns."""
    L = ["\\begin{tabular}{l r r r r r r r r}", "\\toprule",
         "Arm & $n$ & Completed & Checked & Consistent (\\%) & Either rule (\\%)$^\\dagger$ & "
         "Distinct EC$_{50}$ & Largest identical group & Within 1\\% of PMxAgent$^\\S$ \\\\", "\\midrule"]
    nums = [f"\\newcommand{{\\numTtwoPmxEc{k}}}{{{v.replace(',', '{,}')}}}" for k, v in PMX_EC50.items()]
    for a in [a for a in ARMS if by_arm.get(a)]:
        rs = by_arm[a]
        cons = [f(r["summary_consistent_pct"]) for r in rs if f(r.get("summary_consistent_pct")) is not None]
        anyr = [f(r["summary_consistent_any_rule_pct"]) for r in rs
                if f(r.get("summary_consistent_any_rule_pct")) is not None]
        ec = Counter(f"{f(r['ec50']):.3g}" for r in rs if f(r.get("ec50")) is not None)
        pmx = [m for m in map(matches_pmx_ec50, rs) if m is not None]
        vals = {"Completed": str(sum(r["completed"] == "True" for r in rs)), "ConsChecked": str(len(cons)),
                "Cons": f"{st.mean(cons):.1f}" if cons else "--", "ConsAny": f"{st.mean(anyr):.1f}" if anyr else "--",
                "EcDistinct": str(len(ec)), "EcModal": str(max(ec.values(), default=0)),
                "EcConv": str(len(pmx)), "EcPmx": str(sum(pmx))}
        L.append(f"{a} & {len(rs)} & " + " & ".join(vals[k] for k in
                 ("Completed", "ConsChecked", "Cons", "ConsAny", "EcDistinct", "EcModal"))
                 + f" & {vals['EcPmx']} of {vals['EcConv']} \\\\")
        nums += [f"\\newcommand{{{macro('T2_case', a, k)}}}{{{v}}}" for k, v in vals.items()]
    nums.append(f"\\newcommand{{\\numTtwoRuns}}{{{sum(len(by_arm[a]) for a in ARMS if by_arm.get(a))}}}")
    L += ["\\bottomrule", "\\end{tabular}"]
    write("tab_t2_T2_case.tex", L)
    return nums


def t3_accuracy(scores, distinct):
    """tab_accuracy_T3.tex: per arm and T3 task, mean overall accuracy and distinct parameter-value sets."""
    arms = [a for a in ARMS if all(scores[t].get(a) for t in T3)]
    L = ["\\begin{tabular}{l " + "r r " * len(T3) + "}", "\\toprule",
         " & " + " & ".join(f"\\multicolumn{{2}}{{c}}{{{SHORT[t]}}}" for t in T3) + " \\\\",
         " ".join(f"\\cmidrule(lr){{{2 + 2 * i}-{3 + 2 * i}}}" for i in range(len(T3))),
         "Arm" + " & Acc. & Sets" * len(T3) + " \\\\", "\\midrule"]
    for a in arms:
        cells = []
        for t in T3:
            ov = [f(r["overall"]) for r in scores[t][a] if f(r.get("overall")) is not None]
            d = distinct.get((t, a), "n/a")
            cells += [f"{st.mean(ov):.2f}" if ov else "--", "--" if d == "n/a" else d]
        L.append(f"{a} & " + " & ".join(cells) + " \\\\")
    L += ["\\bottomrule", "\\end{tabular}"]
    write("tab_accuracy_T3.tex", L)


def t3_stats(stats):
    """tab_stats_T3.tex: the pre-specified comparisons for every T3 task in one table (T3d exploratory)."""
    L = ["\\begin{tabular}{l l r c c}", "\\toprule",
         "Task & Comparison & Difference (pp) & 95\\% CI & Within $\\pm$1 pp \\\\", "\\midrule"]
    for i, t in enumerate(T3):
        if i:
            L.append("\\addlinespace")
        for r in [r for r in stats if r["task"] == t]:
            L.append(f"{SHORT[t]}{'$^\\ddagger$' if t == 'T3d_oral' else ''} & "
                     f"{r['comparison'].replace('-', '$-$')} & {sg(float(r['diff']))} & "
                     f"{sg(float(r['ci_lo']))} to {sg(float(r['ci_hi']))} & "
                     f"{'yes' if r['equivalent_1pp'] == 'True' else 'no'} \\\\")
    L += ["\\bottomrule", "\\end{tabular}"]
    write("tab_stats_T3.tex", L)


def cost_by_task(scores, runs):
    """tab_cost_T2T3.tex: mean list-price cost per run (USD) by arm and task, T2 and T3."""
    tasks = ["T2_case"] + T3
    arms = [a for a in ARMS if all(scores[t].get(a) for t in tasks)]
    L = ["\\begin{tabular}{l " + "r " * len(tasks) + "}", "\\toprule",
         "Arm & " + " & ".join(SHORT[t] for t in tasks) + " \\\\", "\\midrule"]
    for a in arms:
        cells = []
        for t in tasks:
            c = [f(runs[r["runid"]]["cost_usd"]) for r in scores[t][a] if r["runid"] in runs]
            c = [x for x in c if x is not None]
            cells.append(f"{st.mean(c):.2f}" if c else "--")
        L.append(f"{a} & " + " & ".join(cells) + " \\\\")
    L += ["\\bottomrule", "\\end{tabular}"]
    write("tab_cost_T2T3.tex", L)


if __name__ == "__main__":
    main()
